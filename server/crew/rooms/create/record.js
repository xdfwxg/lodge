import { CHAT_TURNS_PER_ROUND } from '../../room-types/chat.js'
import { roomModeForType } from '../kinds.js'

export const buildRoomRecord = ({
  short,
  title,
  goal,
  handoff,
  receipt,
  transfer,
  templateId,
  plan,
  independence,
  engines,
  models,
  engineFallbacks,
  seatBots,
  seatNames,
  seatRooms,
  chatRoom,
  chatHost = null,
  lead,
  workers,
  verifiers,
  sourceRepo,
  workspaces,
  provider,
  workspaceCaps,
  roomType,
  orchestration,
  builtStages,
  roster,
  align,
  verify,
  acceptance,
  shadowReview = false,
  chatTurnLimit = null,
  parentRoomId = null,
  depth = 0,
  gate = null,
}) => {
  const chatLimit = Number.isInteger(chatTurnLimit) ? chatTurnLimit : CHAT_TURNS_PER_ROUND
  const mode = roomModeForType(roomType.id)
  const shape = mode.record({
    lead,
    plan,
    verify,
    acceptance,
    verifiers,
    independence,
    shadowReview,
    gate,
    builtStages,
    chatLimit,
  })
  return {
  id: `room-${short}`,
  kind: 'room',
  name: title,
  goal,
  ...(handoff === null || handoff === undefined ? {} : { handoff }),
  ...(receipt === null || receipt === undefined ? {} : { receipt }),
  ...(transfer === null || transfer === undefined ? {} : { transfer }),
  templateId,
  plan,
  independence,
  engines,
  models,
  engineFallbacks,
  seatBots,
  seatNames,
  seatRooms,
  chatRoom,
  ...(chatHost === null ? {} : { chatHost }),
  leadSeat: mode.leadSeatOf(lead),
  workers: workers.map(seat => seat.id),
  verifiers: verifiers.map(seat => seat.id),
  sourceRepo,
  branch: workspaces.primaryBranch,
  branches: workspaces.branches,
  worktrees: Object.fromEntries(Object.entries(workspaces.seats).map(([seatId, item]) => [seatId, item.path])),
  ports: workspaces.ports ?? {},
  workspaceEnv: workspaces.environment ?? {},
  repoPath: workspaces.roomPath ?? workspaces.seats[workers[0]?.id ?? lead.id].path,
  workspace: { provider: provider.id, capabilities: workspaceCaps },
  live: true,
  demo: false,
  state: 'active',
  parentRoomId,
  depth,
  childRoomIds: [],
  idle: false,
  round: 0,
  noProgress: 0,
  seatCursors: Object.fromEntries(roster.map(seat => [seat.id, 0])),
  openQuestion: null,
  version: 1,
  seatSpecs: roster.map(({ id, name, title: seatTitle, role, roleKind, roleProfile, isHost, station, engine, model, permissions, writeScope, toolSurface, mcp, approval, speakBudget, personality }) => ({
    id,
    name,
    title: seatTitle,
    role,
    roleKind,
    roleProfile,
    ...(isHost === true ? { isHost: true } : {}),
    station,
    engine,
    ...(model === undefined ? {} : { model }),
    permissions,
    writeScope,
    toolSurface,
    mcp,
    approval,
    speakBudget,
    ...(personality === undefined || personality === '' ? {} : { personality }),
  })),
  constraints: shape.constraints,
  members: roster.map(seat => seat.id),
  roomType: roomType.id,
  engine: shape.engine,
  ...(shape.closure ?? {}),
  orchestration,
  ...(shape.stages === undefined ? {} : { stages: shape.stages }),
  ...(shape.chat === undefined ? {} : { chat: shape.chat }),
  }
}

export const initialRoomMessages = ({
  room,
  plan,
  templateId,
  roster,
  builtStages,
  workspaces,
  engineFallbacks,
}) => roomModeForType(room.roomType).initialMessages({
  room,
  plan,
  templateId,
  roster,
  builtStages,
  workspaces,
  engineFallbacks,
})
