import { CHAT_TURNS_PER_ROUND } from '../../room-types/chat.js'
import { roomModeForType } from '../kinds.js'
import { ROOM_ACCESS } from '../../../../shared/room-access.js'

export const buildRoomRecord = ({
  short,
  title,
  goal,
  handoff,
  receipt,
  transfer,
  templateId,
  plan,
  independence,
  members,
  chatRoom,
  chatHost = null,
  shadowBot = null,
  lead,
  workers,
  verifiers,
  sourceRepo,
  workspaces,
  provider,
  workspaceCaps,
  roomType,
  orchestration,
  shadowReview = false,
  roomAccess = 'ask',
  builtStages,
  align,
  verify,
  acceptance,
  chatTurnLimit = null,
  parentRoomId = null,
  depth = 0,
  gate = null,
}) => {
  const chatLimit = Number.isInteger(chatTurnLimit) ? chatTurnLimit : CHAT_TURNS_PER_ROUND
  const mode = roomModeForType(roomType.id)
  const shape = mode.record({
    lead,
    plan,
    verify,
    acceptance,
    verifiers,
    independence,
    shadowReview,
    gate,
    builtStages,
    chatLimit,
  })
  return {
  id: `room-${short}`,
  kind: 'room',
  name: title,
  goal,
  ...(handoff === null || handoff === undefined ? {} : { handoff }),
  ...(receipt === null || receipt === undefined ? {} : { receipt }),
  ...(transfer === null || transfer === undefined ? {} : { transfer }),
  templateId,
  plan,
  independence,
  members,
  chatRoom,
  ...(chatHost === null ? {} : { chatHost }),
  ...(shadowBot === null ? {} : { shadowBot }),
  leadMemberId: mode.leadMemberIdOf(lead),
  sourceRepo,
  branch: workspaces.primaryBranch,
  branches: workspaces.branches,
  worktrees: Object.fromEntries(Object.entries(workspaces.members).map(([memberId, item]) => [memberId, item.path])),
  ports: workspaces.ports ?? {},
  workspaceEnv: workspaces.environment ?? {},
  repoPath: workspaces.roomPath ?? workspaces.members[workers[0]?.id ?? lead.id].path,
  workspace: { provider: provider.id, capabilities: workspaceCaps },
  live: true,
  demo: false,
  state: 'active',
  ...(roomAccess === ROOM_ACCESS.PUBLIC_WEB ? { roomAccess: ROOM_ACCESS.PUBLIC_WEB } : {}),
  parentRoomId,
  depth,
  childRoomIds: [],
  idle: false,
  round: 0,
  noProgress: 0,
  openQuestion: null,
  version: 1,
  constraints: shape.constraints,
  roomType: roomType.id,
  ...(shape.closure ?? {}),
  orchestration,
  ...(shape.stages === undefined ? {} : { stages: shape.stages }),
  ...(shape.chat === undefined ? {} : { chat: shape.chat }),
  }
}

export const initialRoomMessages = ({
  room,
  plan,
  templateId,
  roster,
  builtStages,
  workspaces,
  engineFallbacks,
  approvalGates = {},
}) => roomModeForType(room.roomType).initialMessages({
  room,
  plan,
  templateId,
  roster,
  builtStages,
  workspaces,
  engineFallbacks,
  approvalGates,
})
