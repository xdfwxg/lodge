import { roomModeForType } from '../kinds.js'
import { ROOM_STATE } from '../../../../shared/states.js'

export const buildRoomRecord = ({
  short,
  title,
  goal,
  handoffBrief,
  receipt,
  transfer,
  templateId,
  plan,
  independence,
  members,
  chatRoom,
  chatHost = null,
  shadowBot = null,
  lead,
  workers,
  verifiers,
  sourceRepo,
  workspaces,
  provider,
  workspaceCaps,
  roomType,
  orchestration,
  shadowReview = false,
  autoDeliver = false,
  builtStages,
  align,
  gate = null,
}) => {
  const mode = roomModeForType(roomType.id)
  const shape = mode.record({
    lead,
    plan,
    verifiers,
    independence,
    shadowReview,
    gate,
    builtStages,
  })
  return {
  id: `room-${short}`,
  kind: 'room',
  name: title,
  goal,
  ...(handoffBrief === null || handoffBrief === undefined ? {} : { handoffBrief }),
  ...(receipt === null || receipt === undefined ? {} : { receipt }),
  ...(transfer === null || transfer === undefined ? {} : { transfer }),
  templateId,
  plan,
  independence,
  members,
  chatRoom,
  ...(chatHost === null ? {} : { chatHost }),
  ...(shadowBot === null ? {} : { shadowBot }),
  leadMemberId: mode.leadMemberIdOf(lead),
  sourceRepo,
  branch: workspaces.primaryBranch,
  branches: workspaces.branches,
  worktrees: Object.fromEntries(Object.entries(workspaces.members).map(([memberId, item]) => [memberId, item.path])),
  ports: workspaces.ports ?? {},
  workspaceEnv: workspaces.environment ?? {},
  repoPath: workspaces.roomPath ?? workspaces.members[workers[0]?.id ?? lead.id].path,
  workspace: { provider: provider.id, capabilities: workspaceCaps },
  live: true,
  demo: false,
  state: ROOM_STATE.active,
  idle: false,
  turnCount: 0,
  noProgress: 0,
  openQuestion: null,
  version: 1,
  constraints: shape.constraints,
  roomType: roomType.id,
  ...(shape.shadowReview === undefined ? {} : { shadowReview: shape.shadowReview }),
  ...(autoDeliver ? { autoDeliver: true } : {}),
  ...(shape.gate === undefined ? {} : { gate: shape.gate }),
  orchestration,
  ...(shape.stages === undefined ? {} : { stages: shape.stages }),
  ...(shape.chat === undefined ? {} : { chat: shape.chat }),
  }
}

export const initialRoomMessages = ({
  room,
  plan,
  templateId,
  roster,
  builtStages,
  workspaces,
  engineFallbacks,
  approvalGates = {},
}) => roomModeForType(room.roomType).initialMessages({
  room,
  plan,
  templateId,
  roster,
  builtStages,
  workspaces,
  engineFallbacks,
  approvalGates,
})
