import { CHAT_TURNS_PER_ROUND } from '../../room-types/chat.js'
import { roomModeForType } from '../kinds.js'

export const buildRoomRecord = ({
  short,
  title,
  goal,
  templateId,
  plan,
  independence,
  engines,
  models,
  engineFallbacks,
  seatBots,
  seatNames,
  seatRooms,
  chatRoom,
  chatHost = null,
  lead,
  workers,
  verifiers,
  sourceRepo,
  workspaces,
  provider,
  workspaceCaps,
  continueSource,
  budgetMicroUsd,
  projectContent,
  projectFile,
  projectPort,
  roomType,
  orchestration,
  builtStages,
  roster,
  align,
  verify,
  acceptance,
  verifierPolicy = 'all',
  shadowReview = false,
  chatTurnLimit = null,
  independencePolicy = 'prefer',
  plannerTools = null,
  gate = null,
  parentRoomId = null,
  depth = 0,
}) => {
  const chatLimit = Number.isInteger(chatTurnLimit) ? chatTurnLimit : CHAT_TURNS_PER_ROUND
  const mode = roomModeForType(roomType.id)
  const shape = mode.record({
    lead,
    plan,
    verify,
    acceptance,
    verifiers,
    independence,
    continueSource,
    verifierPolicy,
    shadowReview,
    independencePolicy,
    plannerTools,
    gate,
    builtStages,
    chatLimit,
  })
  return {
  id: `room-${short}`,
  kind: 'room',
  name: title,
  goal,
  parentRoomId,
  depth,
  childRoomIds: [],
  templateId,
  plan,
  independence,
  engines,
  models,
  engineFallbacks,
  seatBots,
  seatNames,
  seatRooms,
  chatRoom,
  ...(chatHost === null ? {} : { chatHost }),
  leadSeat: mode.leadSeatOf(lead),
  workers: workers.map(seat => seat.id),
  verifiers: verifiers.map(seat => seat.id),
  sourceRepo,
  branch: workspaces.primaryBranch,
  branches: workspaces.branches,
  worktrees: Object.fromEntries(Object.entries(workspaces.seats).map(([seatId, item]) => [seatId, item.path])),
  ports: workspaces.ports ?? {},
  workspaceEnv: workspaces.environment ?? {},
  repoPath: workspaces.roomPath ?? workspaces.seats[workers[0]?.id ?? lead.id].path,
  workspace: { provider: provider.id, capabilities: workspaceCaps },
  ...(continueSource === null
    ? {}
    : { continuedFrom: { roomId: continueSource.id, name: continueSource.name } }),
  live: true,
  demo: false,
  state: 'active',
  ...(shape.trust === undefined ? {} : { trust: shape.trust }),
  idle: false,
  round: 0,
  noProgress: 0,
  seatCursors: Object.fromEntries(roster.map(seat => [seat.id, 0])),
  openQuestion: null,
  version: 1,
  seatSpecs: roster.map(({ id, name, title: seatTitle, role, roleKind, roleProfile, isHost, station, engine, model, permissions, writeScope, toolSurface, skills, mcp, approval, speakBudget }) => ({
    id,
    name,
    title: seatTitle,
    role,
    roleKind,
    roleProfile,
    ...(isHost === true ? { isHost: true } : {}),
    station,
    engine,
    ...(model === undefined ? {} : { model }),
    permissions,
    writeScope,
    toolSurface,
    skills,
    mcp,
    approval,
    speakBudget,
  })),
  constraints: shape.constraints,
  usage: { costMicroUsd: 0, budgetMicroUsd, turns: 0 },
  ...(projectContent === ''
    ? {}
    : {
        projectConstraints: {
          source: projectFile?.layers?.[0]?.name ?? projectPort.file,
          content: projectContent,
          layers: projectFile?.layers ?? [],
        },
      }),
  members: roster.map(seat => seat.id),
  roomType: roomType.id,
  engine: shape.engine,
  ...(shape.closure ?? {}),
  orchestration,
  ...(shape.stages === undefined ? {} : { stages: shape.stages }),
  ...(shape.chat === undefined ? {} : { chat: shape.chat }),
  }
}

export const initialRoomMessages = ({
  room,
  plan,
  templateId,
  roster,
  builtStages,
  continueSource,
  projectContent,
  projectFile,
  workspaces,
  engineFallbacks,
}) => roomModeForType(room.roomType).initialMessages({
  room,
  plan,
  templateId,
  roster,
  builtStages,
  continueSource,
  projectContent,
  projectFile,
  workspaces,
  engineFallbacks,
})
