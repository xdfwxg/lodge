import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

// 席位环境预置：应用可以读取 .lodge/env 与 .lodge/seat-data；
// 它不是 OS 级沙箱，不能阻止应用无视这些变量。
export const writeSeatEnv = ({ room, seatId, path, port }) => {
  if (typeof path !== 'string' || path === '') return null
  const lodge = join(path, '.lodge')
  const data = join(lodge, 'seat-data')
  const tmp = join(lodge, 'tmp')
  mkdirSync(data, { recursive: true })
  mkdirSync(tmp, { recursive: true })
  const values = {
    LODGE_ROOM_ID: room?.id ?? '',
    LODGE_SEAT_ID: seatId ?? '',
    LODGE_SEAT_DATA_DIR: '.lodge/seat-data',
    LODGE_SEAT_TMP: '.lodge/tmp',
    LODGE_PORT: port === undefined ? '' : String(port),
    PORT: port === undefined ? '' : String(port),
    LODGE_WORKSPACE: path,
  }
  const content = [
    '# Generated by Lodge. Application-level seat environment; not an OS sandbox.',
    ...Object.entries(values).map(([key, value]) => `${key}=${value}`),
    '',
  ].join('\n')
  const file = join(lodge, 'env')
  writeFileSync(file, content)
  return { file, data, tmp, values }
}

export const seatEnvFile = path => join(path, '.lodge', 'env')
