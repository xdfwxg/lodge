import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

// 成员环境预置：应用可以读取 .lodge/env 与 .lodge/member-data；
// 它不是 OS 级沙箱，不能阻止应用无视这些变量。
export const writeMemberEnv = ({ room, memberId, path, port }) => {
  if (typeof path !== 'string' || path === '') return null
  const lodge = join(path, '.lodge')
  const data = join(lodge, 'member-data')
  const tmp = join(lodge, 'tmp')
  mkdirSync(data, { recursive: true })
  mkdirSync(tmp, { recursive: true })
  const values = {
    LODGE_ROOM_ID: room?.id ?? '',
    LODGE_MEMBER_ID: memberId ?? '',
    LODGE_MEMBER_DATA_DIR: '.lodge/member-data',
    LODGE_MEMBER_TMP: '.lodge/tmp',
    LODGE_PORT: port === undefined ? '' : String(port),
    PORT: port === undefined ? '' : String(port),
    LODGE_WORKSPACE: path,
  }
  const content = [
    '# Generated by Lodge. Application-level member environment; not an OS sandbox.',
    ...Object.entries(values).map(([key, value]) => `${key}=${value}`),
    '',
  ].join('\n')
  const file = join(lodge, 'env')
  writeFileSync(file, content)
  return { file, data, tmp, values }
}

export const memberEnvFile = path => join(path, '.lodge', 'env')
